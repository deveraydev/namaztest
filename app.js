const modalContent = document.getElementById('modalContent');

document.addEventListener('click', (e)=>{
  const nav = e.target.closest('[data-page]');
  if(nav){ app.page = nav.dataset.page; syncNav(); render(); return; }
  const card = e.target.closest('[data-prayer]');
  if(card){ openPrayer(card.dataset.prayer); return; }
  const part = e.target.closest('[data-part]');
  if(part){ app.currentPart = Number(part.dataset.part); app.currentStep=0; renderPrayerDetail(); return; }
  const next = e.target.closest('[data-next]');
  if(next){ moveStep(1); return; }
  const prev = e.target.closest('[data-prev]');
  if(prev){ moveStep(-1); return; }
  if(e.target.id==='modalClose' || e.target===modal){ closeModal(); }
  const duaBtn=e.target.closest('[data-dua]');
  if(duaBtn){ showDua(duaBtn.dataset.dua); }
});

